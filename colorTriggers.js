function comp(c) {
	var hex = c.toString(16);
	return hex.length == 1 ? "0" + hex : hex;
}

function hex(r, g, b) {
	return "#" + comp(r) + comp(g) + comp(b);
}

function hsv(r, g, b) {
	r = r / 255;
	g = g / 255;
	b = b / 255;
	let max = Math.max(r, g, b);
	let min = Math.min(r, g, b);
	let d = max - min;
	let h;
	if (d == 0) { h = 0 }
	else {
		if (max == r) h = 60 * (((g - b) / d) % 6);
		if (max == g) h = 60 * ((b - r) / d + 2);
		if (max == b) h = 60 * ((r - g) / d + 4);
	}
	let s;
	max == 0 ? s = 0 : s = d / max;
	let v = max;
	h = (h + 360) % 360;
	return [h, s, v];
}

function rgb(h, s, v) {
	let c = v * s;
	let x = c * (1 - Math.abs((h / 60) % 2 - 1));
	let m = v - c;
	let arr = [];
	switch (Math.floor(h / 60)) {
		case 0: arr = [c, x, 0]; break;
		case 1: arr = [x, c, 0]; break;
		case 2: arr = [0, c, x]; break;
		case 3: arr = [0, x, c]; break;
		case 4: arr = [x, 0, c]; break;
		case 5: arr = [c, 0, x];
	}
	return [(arr[0] + m) * 255, (arr[1] + m) * 255, (arr[2] + m) * 255];
}

